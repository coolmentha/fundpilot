-- 用户级 Open API Token：每用户最多一个有效 Token；刷新原地轮换，撤销保留摘要用于审计与防复用。
CREATE TABLE open_api_token (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT,
    created_date TIMESTAMPTZ,
    updated_date TIMESTAMPTZ,
    owner_id BIGINT NOT NULL REFERENCES site_user (id),
    token_hash VARCHAR(64) NOT NULL,
    last_used_at TIMESTAMPTZ,
    rotated_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ
);

-- 每个摘要全生命周期只能存在一次，撤销后也不得被重新签发复用。
CREATE UNIQUE INDEX uq_open_api_token_hash ON open_api_token (token_hash);

-- 同一用户同时只能有一个未撤销 Token。
CREATE UNIQUE INDEX uq_open_api_token_owner_active
    ON open_api_token (owner_id) WHERE revoked_at IS NULL;
