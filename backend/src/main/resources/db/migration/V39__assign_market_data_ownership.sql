    ) THEN
        RAISE EXCEPTION 'active market_indicator_snapshot rows remain without fund_product_id';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM user_config
        WHERE deleted_date IS NULL
          AND watched_indices IS NOT NULL
          AND trim(watched_indices) <> ''
          AND owner_id IS NULL
    ) THEN
        RAISE EXCEPTION 'active watched index configuration remains without owner_id';
    END IF;

    IF (
        SELECT count(*)
        FROM market_watched_index
        WHERE deleted_date IS NULL
    ) <> (
        SELECT count(*)
        FROM (
            SELECT DISTINCT c.owner_id, trim(entry.index_code) AS index_code
            FROM user_config c
            CROSS JOIN LATERAL regexp_split_to_table(c.watched_indices, ',')
                AS entry(index_code)
            WHERE c.deleted_date IS NULL
              AND c.watched_indices IS NOT NULL
              AND trim(entry.index_code) <> ''
        ) expected
    ) THEN
        RAISE EXCEPTION 'market watched index backfill count mismatch';
    END IF;
END $$;
