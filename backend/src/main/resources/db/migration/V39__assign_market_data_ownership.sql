DROP INDEX uq_user_config_singleton;
CREATE UNIQUE INDEX uq_user_config_owner
    ON user_config (owner_id)
    WHERE deleted_date IS NULL;

CREATE TABLE market_watched_index (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    created_date TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_date TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_date TIMESTAMPTZ,
    owner_id BIGINT NOT NULL,
    index_code VARCHAR(64) NOT NULL,
    display_order INTEGER NOT NULL,
    CONSTRAINT fk_market_watched_index_owner
        FOREIGN KEY (owner_id) REFERENCES site_user (id),
    CONSTRAINT ck_market_watched_index_code_not_blank
        CHECK (trim(index_code) <> ''),
    CONSTRAINT ck_market_watched_index_display_order
        CHECK (display_order >= 0)
);

CREATE UNIQUE INDEX uq_market_watched_index_owner_code
    ON market_watched_index (owner_id, index_code)
    WHERE deleted_date IS NULL;
CREATE INDEX idx_market_watched_index_owner_order
    ON market_watched_index (owner_id, display_order)
    WHERE deleted_date IS NULL;

WITH parsed AS (
    SELECT c.owner_id,
           trim(entry.index_code) AS index_code,
           entry.ordinality - 1 AS display_order
    FROM user_config c
    CROSS JOIN LATERAL regexp_split_to_table(c.watched_indices, ',')
        WITH ORDINALITY AS entry(index_code, ordinality)
    WHERE c.deleted_date IS NULL
      AND c.watched_indices IS NOT NULL
      AND trim(entry.index_code) <> ''
), deduplicated AS (
    SELECT owner_id, index_code, min(display_order) AS display_order
    FROM parsed
    GROUP BY owner_id, index_code
)
INSERT INTO market_watched_index (owner_id, index_code, display_order)
SELECT owner_id, index_code, display_order
FROM deduplicated
ORDER BY owner_id, display_order;

