-- MarketData expand migration. Legacy fund references and user_config.watched_indices
-- remain readable until the contract migration.
ALTER TABLE fund_nav_history ADD COLUMN fund_product_id BIGINT;

UPDATE fund_nav_history n
SET fund_product_id = p.id
FROM fund_product p
WHERE p.deleted_date IS NULL
  AND trim(n.fund_code) = p.fund_code;

ALTER TABLE fund_nav_history ADD CONSTRAINT fk_fund_nav_history_product
    FOREIGN KEY (fund_product_id) REFERENCES fund_product (id);
CREATE INDEX idx_fund_nav_history_product_date
    ON fund_nav_history (fund_product_id, nav_date)
    WHERE deleted_date IS NULL;
CREATE UNIQUE INDEX uq_fund_nav_history_product_daily
    ON fund_nav_history (fund_product_id, ((nav_date AT TIME ZONE 'UTC')::date))
    WHERE deleted_date IS NULL;

ALTER TABLE market_indicator_snapshot ADD COLUMN fund_product_id BIGINT;

UPDATE market_indicator_snapshot s
SET fund_product_id = p.id
FROM fund_product p
WHERE p.deleted_date IS NULL
  AND trim(s.fund_code) = p.fund_code;

ALTER TABLE market_indicator_snapshot ADD CONSTRAINT fk_market_indicator_snapshot_product
    FOREIGN KEY (fund_product_id) REFERENCES fund_product (id);
CREATE INDEX idx_market_indicator_snapshot_product_date
    ON market_indicator_snapshot (fund_product_id, snapshot_date)
    WHERE deleted_date IS NULL;
CREATE UNIQUE INDEX uq_market_indicator_snapshot_product_daily
    ON market_indicator_snapshot (fund_product_id, snapshot_date)
    WHERE deleted_date IS NULL;

