    IF EXISTS (
        SELECT 1 FROM fund
        WHERE fund_code IS NOT NULL AND trim(fund_code) <> '' AND product_id IS NULL
    ) THEN
        RAISE EXCEPTION 'fund_product backfill left fund rows without product_id';
    END IF;
END $$;
